"""自建题的测试用例表（唯一真源）。

为什么用例表要独立成文件
------------------------
第一版把用例写死在 ``selfmade_build.py`` 里，结果出现了三类"看不见的错"：

1. **非序列用例依赖了别的用例留下的状态**。例如 self-easy-02 的 c3 断言
   ``alarmHigh=True``，但它其实只是 c2 触发报警后的"记忆"——单周期用例不
   带状态，必挂。这类错只有跑参考解才会暴露。
2. **笔记与期望自相矛盾**。self-medium-01 的 c6 笔记写"运行中不接受装载、
   保持原值"，期望却写成 ``valid=False``。
3. **缺 const_inputs**。数组/结构体输入无法逐周期给出，必须放进
   ``const_inputs`` 由驱动器统一绑定，否则一进 FOR 循环就判非法。

所以这里把用例表集中管理：**带状态语义的一律标 ``seq``（同一题共用一条轨迹），
无状态的一律标 ``single``**，并由 ``selfmade_refs.py`` 用参考解逐条验证。
"""

from __future__ import annotations

from typing import Any

# 配方空槽：recipeID=0
EMPTY_RECIPE = {"recipeID": 0, "totalRatio": 0.0, "temperature": 0.0}


def _slots(*items: dict[str, Any]) -> list[dict[str, Any]]:
    """补满 8 个配方槽，不足的用空槽填充。"""
    out = [dict(x) for x in items]
    while len(out) < 8:
        out.append(dict(EMPTY_RECIPE))
    return out


